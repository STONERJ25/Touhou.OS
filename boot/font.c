#define FONT_COUNT (sizeof(FONT) / sizeof(FONT[0]))

void draw_char(UINT8 *framebuffer, UINT32 stride, INT32 x, INT32 y, INT32 scale, char c, UINT8 r, UINT8 g, UINT8 b) {
    for (UINTN i = 0; i < FONT_COUNT; i++) {
        if (FONT[i].character != c) {
            continue;
        }

        for (INT32 row = 0; row < GLYPH_HEIGHT; row++) {
            UINT8 bits = FONT[i].rows[row];

            for (INT32 col = 0; col < GLYPH_WIDTH; col++) {
                if (bits & (0x80 >> col)) {
                    fill_rect(framebuffer, stride, x + col * scale, y + row * scale, scale, scale, r, g, b);
                }
            }
        }
        return; /* found and drawn -- stop searching */
    }
    /* Unrecognized character: draw nothing rather than garbage. */
}

void draw_string(UINT8 *framebuffer, UINT32 stride, INT32 x, INT32 y, INT32 scale, const char *text, UINT8 r, UINT8 g, UINT8 b) {
    INT32 cursorX = x;

    while (*text != 0) {
        draw_char(framebuffer, stride, cursorX, y, scale, *text, r, g, b);
        cursorX += (GLYPH_WIDTH + 1) * scale; /* +1 column of gap between characters */
        text++;
    }
}
